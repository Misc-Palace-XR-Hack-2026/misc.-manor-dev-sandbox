import { chromium } from '/home/dvgpro/Projects/DataMemoryPalace/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const out = process.env.MP_SCREENSHOTS ?? '/home/dvgpro/.hermes/cache/scratch/preview-25-evidence';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--use-angle=gl', '--enable-webgl', '--ignore-gpu-blocklist'] });
try {
  for (const [name, viewport, isMobile] of [['desktop', {width:1440,height:1000}, false], ['mobile', {width:390,height:844}, true]]) {
    const context = await browser.newContext({ viewport, isMobile, hasTouch:isMobile });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(process.env.MP_URL ?? 'http://127.0.0.1:5187');
    await page.waitForFunction(() => window.store);
    const skip = page.getByRole('button', {name:'Go to room', exact:true});
    if (await skip.isVisible()) await skip.click();
    const id = await page.evaluate(() => window.store.addItem({ title:'Preview fixture',sourceRef:'https://example.com/preview',kind:'book' }));
    const snapshot = await page.evaluate(() => window.store.exportJson());
    const preview = page.getByRole('button', {name:'Preview', exact:true});
    await preview.click({timeout:5000});
    await page.getByRole('button',{name:'Unmute room music',exact:true}).click();
    await page.getByRole('button',{name:'Mute room music',exact:true}).click();
    await page.getByRole('button',{name:'Take photo',exact:true}).click();
    const photo = page.getByRole('dialog',{name:'Room photo',exact:true});
    await photo.getByRole('button',{name:'Download PNG',exact:true}).waitFor();
    assert.ok(await photo.getByAltText('Captured room').evaluate(img=>img.naturalWidth>0));
    await photo.getByRole('button',{name:'Close',exact:true}).click();
    assert.equal(await page.evaluate(()=>window.store.exportJson()), snapshot);
    assert.equal(await page.evaluate(() => window.store.mode), 'preview');
    await page.evaluate(() => window.store.visit({...JSON.parse(window.store.exportJson()), owner:'Visited'}, 'Visited'));
    assert.equal(await page.evaluate(() => window.store.visiting), null);
    assert.equal(await page.evaluate(() => window.store.exportJson()), snapshot);
    await page.evaluate(() => window.store.returnHome());
    assert.equal(await page.evaluate(() => window.store.exportJson()), snapshot);
    assert.equal(await page.getByRole('button', {name:'Add to room',exact:true}).isVisible(), false);
    assert.equal(await page.getByRole('button', {name:'Help',exact:true}).isVisible(), false);
    await page.getByText('Preview · desktop/mobile only. Return to Edit room for VR.', {exact:true}).waitFor();
    assert.equal(await page.locator('.vr-enter').isDisabled(), true);
    const topControls = await page.locator('.vr-enter, .soundtrack-control, .room-capture').evaluateAll(nodes => nodes.map(n => n.getBoundingClientRect().toJSON()));
    for (let i=0;i<topControls.length;i++) for(let j=i+1;j<topControls.length;j++) {
      const a=topControls[i], b=topControls[j];
      assert.ok(a.right<=b.left || b.right<=a.left || a.bottom<=b.top || b.bottom<=a.top, 'top controls must not overlap');
    }
    await page.screenshot({path:`${out}/${name}-preview-idle.png`});
    await page.evaluate(id => window.store.select(id), id);
    const item = page.getByRole('dialog', {name:'Item',exact:true});
    await item.waitFor();
    for (const action of ['Edit','Pick up','Stash','Delete']) assert.equal(await item.getByRole('button',{name:action,exact:true}).count(),0);
    assert.equal(await item.locator('.kind-current').count(),0);
    page.once('dialog', () => { throw new Error('Preview title must not prompt to rename'); });
    await item.locator('.title').dispatchEvent('dblclick');
    const popupPromise = page.waitForEvent('popup');
    await item.getByRole('link', {name:'open',exact:true}).click();
    const popup = await popupPromise;
    await popup.waitForLoadState('domcontentloaded').catch(() => {});
    assert.equal(popup.url(), 'https://example.com/preview');
    await popup.close();
    await page.screenshot({path:`${out}/${name}-preview-inspect.png`});
    assert.equal(await page.evaluate(() => window.store.exportJson()),snapshot);
    await item.getByRole('button',{name:'Close',exact:true}).click();
    const geometry = await page.evaluate(() => ({overflow:document.documentElement.scrollWidth>innerWidth,room:document.querySelector('#room').getBoundingClientRect().toJSON(), buttons:[...document.querySelectorAll('.chrome button')].filter(b=>!b.hidden).map(b=>b.getBoundingClientRect().toJSON())}));
    assert.equal(geometry.overflow,false);
    assert.equal(geometry.room.width,viewport.width);
    for (const b of geometry.buttons) assert.ok(b.height>=44);
    await page.getByTitle('Switch room').click();
    await page.getByRole('dialog',{name:'Rooms',exact:true}).getByRole('button',{name:"Matt's room",exact:true}).click();
    assert.equal(await page.evaluate(()=>window.store.mode),'preview');
    await page.getByTitle('Switch room').click();
    await page.getByRole('dialog',{name:'Rooms',exact:true}).getByRole('button',{name:'My room',exact:true}).click();
    assert.equal(await page.evaluate(() => window.store.exportJson()),snapshot);
    await page.getByRole('button',{name:'Edit room',exact:true}).click();
    await page.getByLabel('Lighting preset').waitFor({state:'visible'});
    await page.getByRole('button',{name:'Close editor',exact:true}).click();
    await page.evaluate(id=>window.store.select(id),id);
    await item.getByRole('button',{name:'Pick up',exact:true}).click();
    assert.equal(await page.evaluate(()=>window.store.holding),id);
    await preview.click();
    assert.equal(await page.evaluate(()=>window.store.holding),null);
    assert.equal(await page.evaluate(()=>window.store.exportJson()),snapshot);
    await item.getByRole('button',{name:'Close',exact:true}).click();
    await page.getByRole('button',{name:'Edit room',exact:true}).click();
    await page.getByRole('button',{name:'Close editor',exact:true}).click();
    await page.evaluate(id=>window.store.select(id),id);
    await item.getByRole('button',{name:'Edit',exact:true}).click();
    await page.getByLabel('Title',{exact:true}).fill('Discard me');
    await page.getByRole('dialog',{name:'Edit item',exact:true}).getByRole('button',{name:'Preview room',exact:true}).click({timeout:5000});
    await page.getByRole('dialog',{name:'Edit item',exact:true}).waitFor({state:'detached'});
    assert.equal(await page.evaluate(()=>window.store.exportJson()),snapshot);
    await page.reload();
    await page.waitForFunction(()=>window.store);
    assert.equal(await page.evaluate(()=>window.store.mode),'edit');
    assert.equal(await page.evaluate(()=>window.store.exportJson()),snapshot);
    // A file read begun in Edit must not land after a Preview → Edit round-trip.
    await page.getByRole('button',{name:'Edit room',exact:true}).click();
    await page.evaluate(() => {
      const original = File.prototype.text;
      File.prototype.text = function () {
        File.prototype.text = original;
        return new Promise(resolve => { window.finishImport = () => resolve(JSON.stringify({...window.store.state, owner:'Late overwrite'})); });
      };
    });
    await page.locator('#menu input[type=file][accept=".json,application/json"]').setInputFiles({name:'room.json',mimeType:'application/json',buffer:Buffer.from('{}')});
    await page.waitForFunction(()=>window.finishImport);
    await page.getByRole('button',{name:'Preview room',exact:true}).click();
    await page.getByRole('button',{name:'Edit room',exact:true}).click();
    await page.evaluate(()=>window.finishImport());
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(()=>window.store.exportJson()),snapshot);
    await page.getByRole('button',{name:'Close editor',exact:true}).click();
    await page.getByRole('button',{name:'Help',exact:true}).click();
    await preview.click();
    assert.equal(await page.locator('.tutorial-overlay').isVisible(),false, 'editing tutorial pauses in Preview');
    assert.deepEqual(errors,[]);
    console.log(`PASS ${name}: Preview, inspect/Open, no mutation, room navigation, pickup restore, draft cancellation, reload, viewport`);
    await context.close();
  }
} finally { await browser.close(); }
