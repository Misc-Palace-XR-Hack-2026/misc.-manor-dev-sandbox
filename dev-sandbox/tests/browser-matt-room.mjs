import { chromium } from '/home/dvgpro/Projects/DataMemoryPalace/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const origin = process.env.MATT_ORIGIN ?? 'http://127.0.0.1:5178';
const evidence = process.env.MATT_EVIDENCE ?? '/home/dvgpro/.hermes/cache/scratch/matt-room-evidence';
mkdirSync(evidence, {recursive: true});
const browser = await chromium.launch({executablePath:'/usr/bin/chromium', headless:true, args:['--use-angle=gl','--enable-webgl','--ignore-gpu-blocklist']});
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin); await page.waitForFunction(() => window.store);
  await page.evaluate(() => localStorage.setItem('mp-sandbox:active-room', 'matt'));
  await page.reload(); await page.waitForFunction(() => window.store?.state.contentItems.length === 14);
  assert.equal(await page.evaluate(() => window.store.state.lighting), 'cyber');
  await page.waitForTimeout(1800);
  await page.screenshot({path:`${evidence}/matt-cyberpunk-desktop.png`});
  await page.evaluate(() => window.store.select('matt-object-clock'));
  const sheet = page.getByRole('dialog', {name:/item/i});
  await sheet.waitFor({state:'visible'});
  assert.match(await sheet.innerText(), /family-owned grandfather/);
  await sheet.getByRole('button', {name:'Edit',exact:true}).click();
  await page.getByLabel('Notes', {exact:true}).fill('Clock research edited locally.');
  await page.getByRole('button', {name:'Save changes',exact:true}).click();
  assert.equal(await page.evaluate(() => window.store.content('matt-clock').notes), 'Clock research edited locally.');
  await page.evaluate(() => window.store.undo());
  await page.waitForTimeout(1000);
  await page.screenshot({path:`${evidence}/matt-clock-notes.png`});
  await sheet.getByRole('button', {name:'Pick up',exact:true}).click();
  assert.equal(await page.evaluate(() => window.store.holding), 'matt-object-clock');
  assert.equal(await sheet.isVisible(), false);
  await page.evaluate(() => {const s=window.store; s.place(s.holding,'floor-5');});
  assert.equal(await page.evaluate(() => window.store.slotOf('matt-object-clock')), 'floor-5');
  await page.reload(); await page.waitForFunction(() => window.store);
  assert.equal(await page.evaluate(() => window.store.slotOf('matt-object-clock')), 'floor-5');
  await page.evaluate(() => {const s=window.store; s.place('matt-object-clock','bench-3'); s.select(null);});
  await page.setViewportSize({width:390,height:844}); await page.waitForTimeout(1200);
  await page.screenshot({path:`${evidence}/matt-cyberpunk-phone.png`});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('PASS: 14-link cyber seed, visible editable notes, UI pickup, placement persistence, desktop/phone WebGL renders; no page errors.');
} finally { await browser.close(); }
